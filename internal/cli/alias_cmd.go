// aliasCmd is agx alias (spec 13.8).
func (c *cliCtx) aliasCmd() *cobra.Command {
	return group("alias", "Shell aliases generated by shell-init",
		c.aliasListCmd(), c.aliasAddCmd(), c.aliasRemoveCmd(),
	)
}

// aliasListCmd is agx alias list.
func (c *cliCtx) aliasListCmd() *cobra.Command {
	cmd := c.newCmd("list", "Shell aliases", CostRead, func(cmd *cobra.Command, args []string) (render.Output, error) {
		rows, err := c.App().AliasList()
		if err != nil {
			return render.Output{}, err
		}
		data, err := render.Encode(rows)
		return render.Output{Data: data, Table: []render.Column{{Header: "NAME", Key: "name"}, {Header: "ARGS", Key: "args"}}}, err
	})
	return fields(cmd, "data.*.name", "data.*.args")
}

// aliasAddCmd is agx alias add.
func (c *cliCtx) aliasAddCmd() *cobra.Command {
	var name, value string
	cmd := c.newCmd("add", "Add or replace an alias", CostWrite, func(cmd *cobra.Command, args []string) (render.Output, error) {
		res, err := c.App().AliasAdd(cmd.Context(), name, value)
		if err != nil {
			return render.Output{}, err
		}
		data, err := render.Encode(res)
		return render.Output{Data: data, Text: func(w io.Writer) error {
			ew := textout.New(w)
			if res.Replaced {
				ew.Line(fmt.Sprintf("alias %s = agx %s (was: agx %s)", res.Name, res.Args, res.Previous))
			} else {
				ew.Line(fmt.Sprintf("alias %s = agx %s", res.Name, res.Args))
			}
			return ew.Err()
		}}, err
	})
	cmd.Example = "  agx alias add --name cl --args \"run --profile personal\"\n  agx alias add --name clr --args resume"
	f := cmd.Flags()
	f.StringVar(&name, "name", "", "the alias name")
	f.StringVar(&value, "args", "", "the agx arguments it runs, named flags only (\"run --profile work\")")
	return fields(cmd, "data.name", "data.args", "data.replaced", "data.previous")
}

// aliasRemoveCmd is agx alias remove.
func (c *cliCtx) aliasRemoveCmd() *cobra.Command {
	var id string
	cmd := c.newCmd("remove", "Remove an alias", CostWrite, func(cmd *cobra.Command, args []string) (render.Output, error) {
		res, err := c.App().AliasRemove(cmd.Context(), id)
		if err != nil {
			return render.Output{}, err
		}
		data, err := render.Encode(res)
		return render.Output{Data: data, Text: func(w io.Writer) error {
			ew := textout.New(w)
			ew.Line("removed alias " + res.Name + " (agx " + res.Args + ")")
			return ew.Err()
		}}, err
	})
	cmd.Flags().StringVar(&id, "id", "", "the alias name")
	return fields(cmd, "data.name", "data.args")
}

// aliasCheck is the alias validator the app checks every alias with (at
// config load, alias add, config check): the charset, then the command
// tree. It only walks the in-memory tree, so it is cheap on every load.
func (c *cliCtx) aliasCheck(args string) error {
	return app.ValidateAlias(args, aliasChecker(c.root))
}

// rawSep ends agx's flags inside an alias, as on the command line.
const rawSep = "--"

// aliasChecker checks an alias value against the command tree under root:
// leading words must name a runnable (non-group, non-hidden) command, and
// every later word is a known flag of that command or the value of the
// flag before it; "--" passes the rest to the agent (spec 5.1).
func aliasChecker(root *cobra.Command) app.AliasChecker {
	return func(args string) error {
		toks := strings.Fields(args)
		i := 0
		for i < len(toks) && !strings.HasPrefix(toks[i], "-") {
			i++
		}
		if i == 0 {
			return errors.New("an alias starts with an agx command, such as \"run --profile work\"")
		}
		cmd, rest, err := root.Find(toks[:i])
		switch {
		case err != nil || cmd == root:
			return fmt.Errorf("%q is not an agx command", strings.Join(toks[:i], " "))
		case cmd.Hidden:
			return fmt.Errorf("agx %s is internal; an alias cannot run it", commandPath(cmd))
		case cmd.HasSubCommands():
			return fmt.Errorf("agx %s needs a verb (%s)", commandPath(cmd), strings.Join(subNames(cmd), ", "))
		case len(rest) > 0:
			return fmt.Errorf("unexpected word %q; every input is a named flag (see agx %s --help)", rest[0], commandPath(cmd))
		}
		for i < len(toks) {
			t := toks[i]
			i++
			if t == rawSep {
				return nil
			}
			f, inline, err := aliasFlag(cmd, t)
			if err != nil {
				return err
			}
			if inline || f.NoOptDefVal != "" {
				continue
			}
			if i >= len(toks) {
				return fmt.Errorf("%s needs a value", t)
			}
			i++
		}
		return nil
	}
}

// aliasFlag finds the flag a token names: --name, --name=value, -x or
// -xvalue. inline is true when the value is in the token itself. A word
// that is not a flag is refused with the named form (spec 5.1 rule 1).
func aliasFlag(cmd *cobra.Command, t string) (*pflag.Flag, bool, error) {
	if !strings.HasPrefix(t, "-") || t == "-" {
		return nil, false, fmt.Errorf("unexpected word %q; every input is a named flag (see agx %s --help)", t, commandPath(cmd))
	}
	if name, ok := strings.CutPrefix(t, "--"); ok {
		name, _, inline := strings.Cut(name, "=")
		f := cmd.Flag(name)
		if f == nil {
			return nil, false, fmt.Errorf("agx %s has no flag --%s", commandPath(cmd), name)
		}
		return f, inline, nil
	}
	short := t[1:2]
	f := cmd.Flags().ShorthandLookup(short)
	if f == nil {
		f = cmd.InheritedFlags().ShorthandLookup(short)
	}
	if f == nil {
		return nil, false, fmt.Errorf("agx %s has no flag -%s", commandPath(cmd), short)
	}
	return f, len(t) > 2, nil
}

// subNames lists a group's visible verbs.
func subNames(cmd *cobra.Command) []string {
	var out []string
	for _, s := range cmd.Commands() {
		if !s.Hidden {
			out = append(out, s.Name())
		}
	}
	return out
}
