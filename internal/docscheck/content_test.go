package docscheck

import (
	"strings"
	"testing"
)

// docsDir is the folder of user guides, relative to the repo root.
const docsDir = "docs"

// localPathMarkers are prefixes of real machine paths that must never reach
// public files; examples use ~ or $HOME instead.
var localPathMarkers = []string{"/Users/", "/Volumes/", "/home/", "/space/"}

// privateMarkers name the private design docs, which readers of the public
// repository cannot open.
var privateMarkers = []string{"docsi"}

// attributionPhrases are authoring-attribution phrases (matched lowercase).
// The products agx runs ("Claude Code", "Codex", "Gemini CLI") are not
// here: naming the subject of the tool is required, crediting a tool for
// the writing is not.
var attributionPhrases = []string{
	"co-authored-by", "generated with", "generated by ai", "claude code-generated",
	"written by claude", "written by ai", "ai-generated", "ai assistant", "copilot",
}

// attributionProductNames are real product identifiers that contain an
// attribution phrase but credit nobody: pi's model provider id
// "github-copilot" and its key variable COPILOT_GITHUB_TOKEN (agentio pi
// tokenEnv), which agx prints in pi's --provider list and login help.
// Matched lowercase, and only as a whole identifier (see
// stripProductNames), so "github-copilot-generated" is still caught.
var attributionProductNames = []string{"github-copilot", "copilot_github_token"}

// firstAttribution returns the attribution phrase line contains, or "",
// after blanking the product names above: the gate stays phrase-precise
// (Copilot credited for the writing in any form is caught) while the real
// pi provider name may appear in examples and docs.
func firstAttribution(line string) string {
	return firstPhrase(stripProductNames(strings.ToLower(line)), attributionPhrases, false)
}

// stripProductNames replaces each whole-identifier occurrence of an
// attributionProductNames entry in a lowercase line with spaces. Whole
// means the bytes on both sides are not identifier bytes (letters, digits,
// "_", "-"), so a longer word that merely contains the name keeps it.
func stripProductNames(line string) string {
	for _, name := range attributionProductNames {
		var b strings.Builder
		rest := line
		for {
			i := strings.Index(rest, name)
			if i < 0 {
				b.WriteString(rest)
				break
			}
			end := i + len(name)
			whole := (i == 0 || !isIdentByte(rest[i-1])) && (end == len(rest) || !isIdentByte(rest[end]))
			b.WriteString(rest[:i])
			if whole {
				b.WriteString(strings.Repeat(" ", len(name)))
			} else {
				b.WriteString(name)
			}
			rest = rest[end:]
		}
		line = b.String()
	}
	return line
}

// isIdentByte reports whether b continues an identifier such as a provider
// id or a variable name (lowercase letters, digits, "_" and "-").
func isIdentByte(b byte) bool {
	return b >= 'a' && b <= 'z' || b >= '0' && b <= '9' || b == '_' || b == '-'
}

// firstPhrase returns the first phrase line contains, or "". fold lowercases
// the line first (the phrases must then be lowercase).
func firstPhrase(line string, phrases []string, fold bool) string {
	if fold {
		line = strings.ToLower(line)
	}
	for _, p := range phrases {
		if strings.Contains(line, p) {
			return p
		}
	}
	return ""
}

// scanLines reports every line of every public markdown file (fenced code
// included) and every example file on which match finds something (it
// returns what it found, or ""), with reason.
func scanLines(t *testing.T, match func(line string) string, reason string) {
	t.Helper()
	root := repoRoot(t)
	for _, f := range publicText(t, root) {
		for i, l := range readLines(t, root, f) {
			if p := match(l); p != "" {
				t.Errorf("%s:%d: %s %q", f, i+1, reason, p)
			}
		}
	}
}

// firstLocalPath returns the first local path marker that starts an
// absolute path in line, or "". A marker preceded by a path-name character
// is the tail of a relative path, not a machine path: the home/ folder of
// an example (examples/x/home/.claude) must not read as /home/.
func firstLocalPath(line string) string {
	for _, m := range localPathMarkers {
		for i := strings.Index(line, m); i >= 0; {
			if i == 0 || !isPathNameByte(line[i-1]) {
				return m
			}
			next := strings.Index(line[i+1:], m)
			if next < 0 {
				break
			}
			i += 1 + next
		}
	}
	return ""
}

// isPathNameByte reports whether b can be part of a file or folder name
// (ASCII letters, digits and the usual name punctuation).
func isPathNameByte(b byte) bool {
	switch {
	case b >= 'a' && b <= 'z', b >= 'A' && b <= 'Z', b >= '0' && b <= '9':
		return true
	}
	return strings.IndexByte("._-", b) >= 0
}

// TestNoLocalPaths fails on a machine path (/Users/, /home/, …) in any
// public doc or example file: readers' paths differ, so docs use ~.
func TestNoLocalPaths(t *testing.T) {
	root := repoRoot(t)
	for _, f := range publicText(t, root) {
		for i, l := range readLines(t, root, f) {
			if p := firstLocalPath(l); p != "" {
				t.Errorf("%s:%d: local machine path (use ~ or $HOME) %q", f, i+1, p)
			}
		}
	}
}

// TestNoPrivateDocs fails when a public file names the private design
// docs, which readers cannot open.
func TestNoPrivateDocs(t *testing.T) {
	scanLines(t, func(l string) string { return firstPhrase(l, privateMarkers, true) }, "mentions the private design docs")
}

// TestNoAttribution fails on an authoring-attribution phrase in a public
// file; naming the agents agx runs is fine.
func TestNoAttribution(t *testing.T) {
	scanLines(t, firstAttribution, "authoring attribution")
}
